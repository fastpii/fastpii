class TestNamesExtractor:
    def test_abstract_cannot_instantiate(self):
        with pytest.raises(TypeError):
            NamesExtractor()

    class CzechStub(NamesExtractor):
        country_code = "CZ"

        def extract(self) -> dict[str, set[str]]:
            return {"male": {"Jan", "Petr"}, "female": {"Jana", "Petra"}}

        def get_source_url(self) -> str:
            return "https://www.czso.cz/"

        def get_license(self) -> str:
            return "Public domain"

    def test_extract(self):
        ext = self.CzechStub()
        data = ext.extract()
        assert "male" in data
        assert "female" in data
        assert "Jan" in data["male"]

    def test_data_type(self):
        ext = self.CzechStub()
        assert ext._data_type() == "Names"

    def test_save(self):
        ext = self.CzechStub()
        with tempfile.TemporaryDirectory() as tmpdir:
            male_path = Path(tmpdir) / "names_male.py"
            female_path = Path(tmpdir) / "names_female.py"
            ext.save(str(male_path), str(female_path))

            male_content = male_path.read_text()
            assert "MALE_NAMES" in male_content
            assert '"jan"' in male_content

            female_content = female_path.read_text()
            assert "FEMALE_NAMES" in female_content
            assert '"jana"' in female_content