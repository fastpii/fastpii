"""Tests for fastpii.data.extractors module."""

import tempfile
from pathlib import Path

import pytest

from fastpii.data.base import DataSource
from fastpii.data.extractors.base import BaseExtractor
from fastpii.data.extractors.bank_codes import BankCodesExtractor
from fastpii.data.extractors.cities import CitiesExtractor
from fastpii.data.extractors.postal_codes import PostalCodesExtractor
from fastpii.data.extractors.names import NamesExtractor


class StubExtractor(BaseExtractor):
    """Concrete stub for testing BaseExtractor."""

    country_code = "XX"

    def extract(self) -> dict[str, str]:
        return {"0100": "Test Bank"}

    def get_source_url(self) -> str:
        return "https://example.com"

    def get_license(self) -> str:
        return "MIT"


class TestBaseExtractor:
    def test_abstract_cannot_instantiate(self):
        with pytest.raises(TypeError):
            BaseExtractor()

    def test_concrete_subclass(self):
        ext = StubExtractor()
        assert ext.country_code == "XX"
        assert ext.extract() == {"0100": "Test Bank"}
        assert ext.get_source_url() == "https://example.com"
        assert ext.get_license() == "MIT"

    def test_get_source(self):
        ext = StubExtractor()
        source = ext.get_source(entry_count=42)
        assert isinstance(source, DataSource)
        assert source.name == "XX Data"
        assert source.url == "https://example.com"
        assert source.license == "MIT"
        assert source.entry_count == 42

    def test_data_type_default(self):
        ext = StubExtractor()
        assert ext._data_type() == "Data"

    def test_write_header(self):
        ext = StubExtractor()
        source = DataSource(
            name="XX Data", url="https://example.com", license="MIT",
            last_updated=__import__("datetime").datetime(2025, 1, 15), entry_count=42,
        )
        with tempfile.NamedTemporaryFile(mode="w", suffix=".py", delete=False) as f:
            ext._write_header(f, source)
            path = Path(f.name)

        content = path.read_text()
        assert "# Auto-generated by FastPII data extractor" in content
        assert "# Country: XX" in content
        assert "# Source: https://example.com" in content
        assert "# License: MIT" in content
        assert "# Entries: 42" in content
        path.unlink()


